"""
Model experiment configuration engine for NeuroPilots.

This module manages model-side experiment changes generated by the AI
Research Advisor.

Responsibilities:
    - Represent model experiment changes.
    - Apply hyperparameter/configuration overrides.
    - Validate experiment parameters.
    - Preserve the original configuration.
    - Produce an auditable experiment configuration.
    - Support generic model-side changes without hardcoding a particular
      diagnosis-to-recommendation mapping.

Important design principle:
    The LLM decides WHAT experiment should be tried.

    This module decides HOW that experiment configuration can be represented
    and validated for execution.

For example, the LLM may generate:
    "Increase weight decay to 0.01"

This engine can represent that as:
    {"weight_decay": 0.01}

It does NOT contain logic such as:
    if root_cause == "overfitting":
        weight_decay = 0.01

That separation keeps recommendation generation dynamic.
"""

from __future__ import annotations

import copy
import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional

from utils.logger import get_logger


LOGGER = get_logger(__name__)


# ---------------------------------------------------------------------------
# Supported model experiment categories
# ---------------------------------------------------------------------------

EXPERIMENT_HYPERPARAMETER = "hyperparameter"
EXPERIMENT_OPTIMIZER = "optimizer"
EXPERIMENT_MODEL_CONFIGURATION = "model_configuration"
EXPERIMENT_REGULARIZATION = "regularization"
EXPERIMENT_LEARNING_RATE = "learning_rate"
EXPERIMENT_BATCH_SIZE = "batch_size"

SUPPORTED_EXPERIMENT_TYPES = (
    EXPERIMENT_HYPERPARAMETER,
    EXPERIMENT_OPTIMIZER,
    EXPERIMENT_MODEL_CONFIGURATION,
    EXPERIMENT_REGULARIZATION,
    EXPERIMENT_LEARNING_RATE,
    EXPERIMENT_BATCH_SIZE,
)


# ---------------------------------------------------------------------------
# Result model
# ---------------------------------------------------------------------------


@dataclass
class ModelExperimentResult:
    """
    Result produced by ModelExperimentEngine.

    Attributes:
        success:
            Whether the model experiment configuration was created
            successfully.

        experiment_type:
            Category of the model-side experiment.

        original_configuration:
            Configuration before applying the experiment.

        experiment_configuration:
            Configuration after applying the requested changes.

        changes:
            Human-readable list of changes.

        changed_parameters:
            Mapping containing only parameters changed by this experiment.

        validation_errors:
            Validation errors encountered during configuration validation.

        metadata:
            Additional execution information.

        error:
            Error message when configuration creation fails.
    """

    success: bool
    experiment_type: str
    original_configuration: Dict[str, Any] = field(default_factory=dict)
    experiment_configuration: Dict[str, Any] = field(default_factory=dict)
    changes: List[str] = field(default_factory=list)
    changed_parameters: Dict[str, Any] = field(default_factory=dict)
    validation_errors: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)
    error: Optional[str] = None


# ---------------------------------------------------------------------------
# Model Experiment Engine
# ---------------------------------------------------------------------------


class ModelExperimentEngine:
    """
    Prepare and validate model-side experiment configurations.

    The engine works with configuration dictionaries instead of depending on
    a specific ML framework. This allows the same execution layer to be used
    by different workload implementations.

    Example:

        engine = ModelExperimentEngine()

        result = engine.apply(
            {"learning_rate": 0.001, "batch_size": 32},
            experiment_type="hyperparameter",
            changes={"learning_rate": 0.0005},
        )

    The original configuration remains unchanged.
    """

    def __init__(
        self,
        strict_validation: bool = True,
    ) -> None:
        self.strict_validation = strict_validation

        LOGGER.info(
            "ModelExperimentEngine initialized with strict_validation=%s",
            self.strict_validation,
        )

    # -----------------------------------------------------------------------
    # Public API
    # -----------------------------------------------------------------------

    def apply(
        self,
        configuration: Optional[Mapping[str, Any]],
        experiment_type: str = EXPERIMENT_HYPERPARAMETER,
        changes: Optional[Mapping[str, Any]] = None,
        **kwargs: Any,
    ) -> ModelExperimentResult:
        """
        Apply model experiment changes to a configuration.

        Args:
            configuration:
                Current model/training configuration.

            experiment_type:
                Type of model experiment.

            changes:
                Parameter overrides to apply.

            **kwargs:
                Additional parameters accepted for future extensions.

        Returns:
            ModelExperimentResult.

        Raises:
            TypeError:
                If configuration or changes have an invalid type.

            ValueError:
                If experiment_type is unsupported.
        """
        normalized_type = self._normalize_experiment_type(
            experiment_type
        )

        if normalized_type not in SUPPORTED_EXPERIMENT_TYPES:
            raise ValueError(
                f"Unsupported experiment type '{experiment_type}'. "
                f"Supported types: {SUPPORTED_EXPERIMENT_TYPES}"
            )

        original = self._prepare_configuration(configuration)
        requested_changes = self._prepare_changes(changes)

        LOGGER.info(
            "Applying model experiment: type=%s, changes=%d",
            normalized_type,
            len(requested_changes),
        )

        try:
            experiment_configuration = copy.deepcopy(original)

            for parameter, value in requested_changes.items():
                experiment_configuration[parameter] = copy.deepcopy(value)

            validation_errors = self.validate_configuration(
                experiment_configuration,
                experiment_type=normalized_type,
            )

            if validation_errors and self.strict_validation:
                LOGGER.warning(
                    "Model experiment validation failed with %d error(s).",
                    len(validation_errors),
                )

                return ModelExperimentResult(
                    success=False,
                    experiment_type=normalized_type,
                    original_configuration=original,
                    experiment_configuration=experiment_configuration,
                    changed_parameters=requested_changes,
                    validation_errors=validation_errors,
                    metadata={
                        "strict_validation": self.strict_validation,
                    },
                    error="Model experiment configuration failed validation.",
                )

            actual_changes = self._get_changed_parameters(
                original,
                experiment_configuration,
            )

            change_descriptions = self._describe_changes(
                actual_changes
            )

            return ModelExperimentResult(
                success=True,
                experiment_type=normalized_type,
                original_configuration=original,
                experiment_configuration=experiment_configuration,
                changes=change_descriptions,
                changed_parameters=actual_changes,
                validation_errors=validation_errors,
                metadata={
                    "strict_validation": self.strict_validation,
                    "additional_arguments": dict(kwargs),
                },
            )

        except Exception as exc:
            LOGGER.exception(
                "Model experiment configuration failed."
            )

            return ModelExperimentResult(
                success=False,
                experiment_type=normalized_type,
                original_configuration=original,
                changed_parameters=requested_changes,
                metadata={
                    "strict_validation": self.strict_validation,
                },
                error=str(exc),
            )

    # -----------------------------------------------------------------------
    # Configuration validation
    # -----------------------------------------------------------------------

    def validate_configuration(
        self,
        configuration: Mapping[str, Any],
        experiment_type: str = EXPERIMENT_HYPERPARAMETER,
    ) -> List[str]:
        """
        Validate a model/training configuration.

        Validation is intentionally generic and framework-independent.

        Known parameters receive semantic validation:
            learning_rate > 0
            batch_size > 0
            epochs > 0
            weight_decay >= 0
            dropout between 0 and 1

        Unknown parameters are allowed because different workloads and models
        can expose different configuration fields.
        """
        if not isinstance(configuration, Mapping):
            raise TypeError(
                "configuration must be a mapping."
            )

        errors: List[str] = []

        # Validate known numeric parameters when present.
        if "learning_rate" in configuration:
            errors.extend(
                self._validate_positive_number(
                    "learning_rate",
                    configuration["learning_rate"],
                )
            )

        if "batch_size" in configuration:
            errors.extend(
                self._validate_positive_integer(
                    "batch_size",
                    configuration["batch_size"],
                )
            )

        if "epochs" in configuration:
            errors.extend(
                self._validate_positive_integer(
                    "epochs",
                    configuration["epochs"],
                )
            )

        if "weight_decay" in configuration:
            errors.extend(
                self._validate_non_negative_number(
                    "weight_decay",
                    configuration["weight_decay"],
                )
            )

        if "dropout" in configuration:
            errors.extend(
                self._validate_probability(
                    "dropout",
                    configuration["dropout"],
                )
            )

        if "momentum" in configuration:
            errors.extend(
                self._validate_probability(
                    "momentum",
                    configuration["momentum"],
                )
            )

        if experiment_type == EXPERIMENT_LEARNING_RATE:
            if "learning_rate" not in configuration:
                errors.append(
                    "learning_rate experiment requires a learning_rate value."
                )

        if experiment_type == EXPERIMENT_BATCH_SIZE:
            if "batch_size" not in configuration:
                errors.append(
                    "batch_size experiment requires a batch_size value."
                )

        return errors

    # -----------------------------------------------------------------------
    # Convenience APIs
    # -----------------------------------------------------------------------

    def update_hyperparameters(
        self,
        configuration: Optional[Mapping[str, Any]],
        changes: Mapping[str, Any],
    ) -> ModelExperimentResult:
        """
        Apply generic hyperparameter changes.
        """
        return self.apply(
            configuration,
            experiment_type=EXPERIMENT_HYPERPARAMETER,
            changes=changes,
        )

    def update_learning_rate(
        self,
        configuration: Optional[Mapping[str, Any]],
        learning_rate: float,
    ) -> ModelExperimentResult:
        """
        Apply a learning-rate experiment.
        """
        return self.apply(
            configuration,
            experiment_type=EXPERIMENT_LEARNING_RATE,
            changes={
                "learning_rate": learning_rate,
            },
        )

    def update_batch_size(
        self,
        configuration: Optional[Mapping[str, Any]],
        batch_size: int,
    ) -> ModelExperimentResult:
        """
        Apply a batch-size experiment.
        """
        return self.apply(
            configuration,
            experiment_type=EXPERIMENT_BATCH_SIZE,
            changes={
                "batch_size": batch_size,
            },
        )

    def update_model_configuration(
        self,
        configuration: Optional[Mapping[str, Any]],
        changes: Mapping[str, Any],
    ) -> ModelExperimentResult:
        """
        Apply model-architecture/configuration changes.

        The engine does not restrict unknown model-specific parameters.
        Workload-specific engines can perform additional validation later.
        """
        return self.apply(
            configuration,
            experiment_type=EXPERIMENT_MODEL_CONFIGURATION,
            changes=changes,
        )

    def supports(self, experiment_type: str) -> bool:
        """
        Return whether an experiment type is supported.
        """
        normalized = self._normalize_experiment_type(
            experiment_type
        )

        return normalized in SUPPORTED_EXPERIMENT_TYPES

    def supported_experiment_types(self) -> List[str]:
        """
        Return all supported experiment types.
        """
        return list(SUPPORTED_EXPERIMENT_TYPES)

    # -----------------------------------------------------------------------
    # Recommendation helper
    # -----------------------------------------------------------------------

    def extract_parameter_changes(
        self,
        recommendation_text: str,
    ) -> Dict[str, Any]:
        """
        Extract a small set of explicitly stated parameter assignments from
        recommendation text.

        This helper is intentionally conservative.

        It does NOT infer a parameter value from a root cause.

        For example:

            "Set learning_rate to 0.0005"

        can be extracted as:

            {"learning_rate": 0.0005}

        But a vague statement such as:

            "Reduce the learning rate"

        returns an empty dictionary because the actual value was not provided.

        This prevents the execution layer from silently inventing
        hyperparameters.
        """
        if not isinstance(recommendation_text, str):
            raise TypeError(
                "recommendation_text must be a string."
            )

        text = recommendation_text.lower()

        extracted: Dict[str, Any] = {}

        # This parser intentionally recognizes explicit assignments only.
        patterns = (
            ("learning_rate", "learning rate"),
            ("batch_size", "batch size"),
            ("weight_decay", "weight decay"),
            ("dropout", "dropout"),
            ("epochs", "epochs"),
        )

        for parameter, phrase in patterns:
            position = text.find(phrase)

            if position == -1:
                continue

            suffix = text[position + len(phrase):]

            value = self._extract_first_number(suffix)

            if value is None:
                continue

            if parameter in {"batch_size", "epochs"}:
                if float(value).is_integer():
                    extracted[parameter] = int(value)
            else:
                extracted[parameter] = value

        return extracted

    # -----------------------------------------------------------------------
    # Internal helpers
    # -----------------------------------------------------------------------

    @staticmethod
    def _prepare_configuration(
        configuration: Optional[Mapping[str, Any]],
    ) -> Dict[str, Any]:
        """
        Create an isolated copy of the configuration.
        """
        if configuration is None:
            return {}

        if not isinstance(configuration, Mapping):
            raise TypeError(
                "configuration must be a mapping."
            )

        return copy.deepcopy(dict(configuration))

    @staticmethod
    def _prepare_changes(
        changes: Optional[Mapping[str, Any]],
    ) -> Dict[str, Any]:
        """
        Validate and copy requested changes.
        """
        if changes is None:
            return {}

        if not isinstance(changes, Mapping):
            raise TypeError(
                "changes must be a mapping."
            )

        return copy.deepcopy(dict(changes))

    @staticmethod
    def _normalize_experiment_type(
        experiment_type: str,
    ) -> str:
        """
        Normalize experiment type names.
        """
        if not isinstance(experiment_type, str):
            raise TypeError(
                "experiment_type must be a string."
            )

        return (
            experiment_type
            .strip()
            .lower()
            .replace("-", "_")
            .replace(" ", "_")
        )

    @staticmethod
    def _get_changed_parameters(
        original: Mapping[str, Any],
        updated: Mapping[str, Any],
    ) -> Dict[str, Any]:
        """
        Return only parameters whose values changed.
        """
        changed: Dict[str, Any] = {}

        all_keys = set(original) | set(updated)

        for key in all_keys:
            original_value = original.get(key)
            updated_value = updated.get(key)

            if original_value != updated_value:
                changed[key] = copy.deepcopy(updated_value)

        return changed

    @staticmethod
    def _describe_changes(
        changes: Mapping[str, Any],
    ) -> List[str]:
        """
        Convert changed parameters into human-readable descriptions.
        """
        descriptions: List[str] = []

        for parameter, value in changes.items():
            descriptions.append(
                f"Set '{parameter}' to {value!r}."
            )

        return descriptions

    @staticmethod
    def _validate_positive_number(
        parameter: str,
        value: Any,
    ) -> List[str]:
        """
        Validate a strictly positive numeric value.
        """
        if isinstance(value, bool) or not isinstance(
            value,
            (int, float),
        ):
            return [
                f"{parameter} must be a numeric value."
            ]

        if not math.isfinite(float(value)):
            return [
                f"{parameter} must be finite."
            ]

        if float(value) <= 0:
            return [
                f"{parameter} must be greater than zero."
            ]

        return []

    @staticmethod
    def _validate_non_negative_number(
        parameter: str,
        value: Any,
    ) -> List[str]:
        """
        Validate a non-negative numeric value.
        """
        if isinstance(value, bool) or not isinstance(
            value,
            (int, float),
        ):
            return [
                f"{parameter} must be a numeric value."
            ]

        if not math.isfinite(float(value)):
            return [
                f"{parameter} must be finite."
            ]

        if float(value) < 0:
            return [
                f"{parameter} must be greater than or equal to zero."
            ]

        return []

    @staticmethod
    def _validate_positive_integer(
        parameter: str,
        value: Any,
    ) -> List[str]:
        """
        Validate a strictly positive integer.
        """
        if isinstance(value, bool) or not isinstance(value, int):
            return [
                f"{parameter} must be an integer."
            ]

        if value <= 0:
            return [
                f"{parameter} must be greater than zero."
            ]

        return []

    @staticmethod
    def _validate_probability(
        parameter: str,
        value: Any,
    ) -> List[str]:
        """
        Validate a value in [0, 1].
        """
        if isinstance(value, bool) or not isinstance(
            value,
            (int, float),
        ):
            return [
                f"{parameter} must be numeric."
            ]

        if not math.isfinite(float(value)):
            return [
                f"{parameter} must be finite."
            ]

        if not 0.0 <= float(value) <= 1.0:
            return [
                f"{parameter} must be between 0 and 1."
            ]

        return []

    @staticmethod
    def _extract_first_number(
        text: str,
    ) -> Optional[float]:
        """
        Extract the first simple numeric value from text.

        Supports:
            0.001
            1e-4
            32
            0.5
        """
        import re

        match = re.search(
            r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?",
            text,
        )

        if match is None:
            return None

        try:
            return float(match.group(0))
        except ValueError:
            return None

    def __repr__(self) -> str:
        """
        Developer-friendly representation.
        """
        return (
            "ModelExperimentEngine("
            f"strict_validation={self.strict_validation}"
            ")"
        )