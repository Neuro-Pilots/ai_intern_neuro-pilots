"""
Experiment selection for the NeuroPilots AI Research Advisor.

The ExperimentSelector is responsible for evaluating a structured experiment
recommendation and deciding whether it is suitable for execution.

Important design principle:
    The selector does NOT generate or hardcode recommendations.

Recommendation generation is performed by the LLMReasoner and structured by
the RecommendationEngine. This module only evaluates the resulting
ExperimentRecommendation against the available ExperimentContext.

Responsibilities:
    1. Validate that a recommendation is executable in the current context.
    2. Evaluate recommendation completeness.
    3. Check workload compatibility.
    4. Check whether the required evidence/artifacts are available.
    5. Produce an explainable selection decision.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from config.settings import LOG_LEVEL
from diagnostics.failure_modes import is_failure_mode_supported
from utils.constants import SUPPORTED_WORKLOADS
from utils.logger import get_logger
from utils.models import (
    Diagnosis,
    ExperimentContext,
    ExperimentRecommendation,
)


LOGGER = get_logger(__name__)


# ---------------------------------------------------------------------------
# Selection thresholds
# ---------------------------------------------------------------------------

# Minimum score required for an experiment to be considered executable.
#
# The score is based on generic execution-readiness criteria rather than
# mapping a particular diagnosis to a particular recommendation.
MINIMUM_SELECTION_SCORE = 0.60

# Score contribution for each generic criterion.
SCORE_WEIGHTS = {
    "title": 0.15,
    "change": 0.25,
    "reason": 0.15,
    "context": 0.15,
    "diagnosis": 0.15,
    "artifacts": 0.15,
}


# ---------------------------------------------------------------------------
# Result model
# ---------------------------------------------------------------------------


@dataclass
class ExperimentSelectionResult:
    """
    Result produced by ExperimentSelector.

    Attributes:
        selected:
            Whether the recommendation is suitable for execution.

        score:
            Generic execution-readiness score in the range [0, 1].

        reasons:
            Human-readable reasons supporting the selection decision.

        blockers:
            Issues that prevent the recommendation from being safely selected.

        checks:
            Individual selection checks and their results.

        recommendation:
            The original structured recommendation.

        metadata:
            Additional diagnostic information useful for logging/debugging.
    """

    selected: bool
    score: float
    reasons: List[str] = field(default_factory=list)
    blockers: List[str] = field(default_factory=list)
    checks: Dict[str, bool] = field(default_factory=dict)
    recommendation: Optional[ExperimentRecommendation] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


# ---------------------------------------------------------------------------
# Selector
# ---------------------------------------------------------------------------


class ExperimentSelector:
    """
    Evaluate whether a generated experiment recommendation is ready to execute.

    This class deliberately does not contain workload-specific recommendation
    mappings. For example, it does not contain logic such as:

        if overfitting:
            recommend_dropout()

    Instead, it evaluates whatever recommendation the LLM produced.

    Args:
        minimum_score:
            Minimum execution-readiness score required for selection.
    """

    def __init__(
        self,
        minimum_score: float = MINIMUM_SELECTION_SCORE,
    ) -> None:
        if not 0.0 <= minimum_score <= 1.0:
            raise ValueError("minimum_score must be between 0.0 and 1.0")

        self.minimum_score = minimum_score

        LOGGER.info(
            "ExperimentSelector initialized with minimum_score=%.2f",
            self.minimum_score,
        )

    # -----------------------------------------------------------------------
    # Public API
    # -----------------------------------------------------------------------

    def select(
        self,
        recommendation: ExperimentRecommendation,
        context: Optional[ExperimentContext] = None,
    ) -> ExperimentSelectionResult:
        """
        Evaluate a recommendation for execution.

        Args:
            recommendation:
                Structured recommendation generated by RecommendationEngine.

            context:
                Current experiment context containing workload, artifacts,
                performance analysis, and diagnosis.

        Returns:
            ExperimentSelectionResult containing the selection decision.
        """
        if not isinstance(recommendation, ExperimentRecommendation):
            raise TypeError(
                "recommendation must be an ExperimentRecommendation instance"
            )

        LOGGER.info(
            "Evaluating experiment recommendation: %s",
            recommendation.title,
        )

        checks: Dict[str, bool] = {}
        reasons: List[str] = []
        blockers: List[str] = []

        # ---------------------------------------------------------------
        # 1. Recommendation completeness
        # ---------------------------------------------------------------

        completeness_score, completeness_checks, completeness_reasons = (
            self._evaluate_completeness(recommendation)
        )

        checks.update(completeness_checks)
        reasons.extend(completeness_reasons)

        # ---------------------------------------------------------------
        # 2. Context availability
        # ---------------------------------------------------------------

        context_score, context_checks, context_reasons, context_blockers = (
            self._evaluate_context(context)
        )

        checks.update(context_checks)
        reasons.extend(context_reasons)
        blockers.extend(context_blockers)

        # ---------------------------------------------------------------
        # 3. Diagnosis consistency
        # ---------------------------------------------------------------

        diagnosis_score, diagnosis_checks, diagnosis_reasons, diagnosis_blockers = (
            self._evaluate_diagnosis(context)
        )

        checks.update(diagnosis_checks)
        reasons.extend(diagnosis_reasons)
        blockers.extend(diagnosis_blockers)

        # ---------------------------------------------------------------
        # 4. Artifact availability
        # ---------------------------------------------------------------

        artifact_score, artifact_checks, artifact_reasons = (
            self._evaluate_artifacts(context)
        )

        checks.update(artifact_checks)
        reasons.extend(artifact_reasons)

        # ---------------------------------------------------------------
        # Calculate overall score
        # ---------------------------------------------------------------

        score = self._calculate_score(
            recommendation=recommendation,
            context=context,
            completeness_score=completeness_score,
            context_score=context_score,
            diagnosis_score=diagnosis_score,
            artifact_score=artifact_score,
        )

        # ---------------------------------------------------------------
        # Hard blockers override score.
        # ---------------------------------------------------------------

        selected = score >= self.minimum_score and not blockers

        if selected:
            reasons.append(
                "Recommendation passed the execution-readiness checks."
            )
        else:
            if score < self.minimum_score:
                blockers.append(
                    "Execution-readiness score is below the required threshold."
                )

            if blockers:
                reasons.append(
                    "Recommendation was not selected because execution blockers "
                    "were detected."
                )

        result = ExperimentSelectionResult(
            selected=selected,
            score=round(score, 4),
            reasons=self._unique(reasons),
            blockers=self._unique(blockers),
            checks=checks,
            recommendation=recommendation,
            metadata={
                "minimum_score": self.minimum_score,
                "log_level": LOG_LEVEL,
            },
        )

        LOGGER.info(
            "Experiment selection completed: selected=%s, score=%.3f, blockers=%d",
            result.selected,
            result.score,
            len(result.blockers),
        )

        return result

    # -----------------------------------------------------------------------
    # Recommendation checks
    # -----------------------------------------------------------------------

    def _evaluate_completeness(
        self,
        recommendation: ExperimentRecommendation,
    ) -> tuple[float, Dict[str, bool], List[str]]:
        """
        Evaluate whether the recommendation contains enough information.

        The recommendation must contain:
            - title
            - change
            - reason

        Optional fields such as expected improvement, cost, and priority do
        not prevent execution because the LLM may legitimately omit them.
        """
        checks: Dict[str, bool] = {}
        reasons: List[str] = []

        title_valid = bool(recommendation.title.strip())
        change_valid = bool(recommendation.change.strip())
        reason_valid = bool(recommendation.reason.strip())

        checks["recommendation_has_title"] = title_valid
        checks["recommendation_has_change"] = change_valid
        checks["recommendation_has_reason"] = reason_valid

        if title_valid:
            reasons.append("Recommendation contains a clear experiment title.")
        else:
            reasons.append("Recommendation is missing an experiment title.")

        if change_valid:
            reasons.append("Recommendation specifies a concrete change.")
        else:
            reasons.append("Recommendation does not specify a concrete change.")

        if reason_valid:
            reasons.append("Recommendation explains why the change is proposed.")
        else:
            reasons.append("Recommendation does not provide a reason.")

        valid_count = sum(
            [title_valid, change_valid, reason_valid]
        )

        score = valid_count / 3.0

        return score, checks, reasons

    # -----------------------------------------------------------------------
    # Context checks
    # -----------------------------------------------------------------------

    def _evaluate_context(
        self,
        context: Optional[ExperimentContext],
    ) -> tuple[float, Dict[str, bool], List[str], List[str]]:
        """
        Evaluate whether enough experiment context exists.

        A selector can still inspect a recommendation without context, but
        execution selection should be conservative when context is missing.
        """
        checks: Dict[str, bool] = {}
        reasons: List[str] = []
        blockers: List[str] = []

        if context is None:
            checks["context_available"] = False
            checks["workload_supported"] = False

            blockers.append(
                "Experiment context is unavailable; workload and artifacts "
                "cannot be verified."
            )

            return 0.0, checks, reasons, blockers

        checks["context_available"] = True
        reasons.append("Experiment context is available.")

        workload_valid = context.workload in SUPPORTED_WORKLOADS

        checks["workload_supported"] = workload_valid

        if workload_valid:
            reasons.append(
                f"Workload '{context.workload}' is supported."
            )
        else:
            blockers.append(
                f"Workload '{context.workload}' is not supported."
            )

        return (
            1.0 if workload_valid else 0.0,
            checks,
            reasons,
            blockers,
        )

    # -----------------------------------------------------------------------
    # Diagnosis checks
    # -----------------------------------------------------------------------

    def _evaluate_diagnosis(
        self,
        context: Optional[ExperimentContext],
    ) -> tuple[float, Dict[str, bool], List[str], List[str]]:
        """
        Evaluate whether the recommendation has diagnostic context.

        The selector does not decide whether a diagnosis is correct. That is
        the responsibility of RootCauseEngine. Here we only verify that the
        recommendation is associated with a valid diagnostic context.
        """
        checks: Dict[str, bool] = {}
        reasons: List[str] = []
        blockers: List[str] = []

        if context is None or context.diagnosis is None:
            checks["diagnosis_available"] = False

            blockers.append(
                "No diagnosis is available to justify the experiment selection."
            )

            return 0.0, checks, reasons, blockers

        diagnosis: Diagnosis = context.diagnosis

        checks["diagnosis_available"] = True

        if diagnosis.primary_root_cause is None:
            checks["primary_root_cause_available"] = False

            reasons.append(
                "Diagnosis is available, but no primary root cause was identified."
            )

            return 0.5, checks, reasons, blockers

        checks["primary_root_cause_available"] = True

        root_cause = diagnosis.primary_root_cause.name

        supported = is_failure_mode_supported(root_cause)
        checks["primary_root_cause_supported"] = supported

        if supported:
            reasons.append(
                f"Recommendation is associated with supported root cause "
                f"'{root_cause}'."
            )
        else:
            blockers.append(
                f"Primary root cause '{root_cause}' is not a supported failure mode."
            )

        return (
            1.0 if supported else 0.0,
            checks,
            reasons,
            blockers,
        )

    # -----------------------------------------------------------------------
    # Artifact checks
    # -----------------------------------------------------------------------

    def _evaluate_artifacts(
        self,
        context: Optional[ExperimentContext],
    ) -> tuple[float, Dict[str, bool], List[str]]:
        """
        Evaluate whether the experiment has usable artifacts.

        The selector does not assume that every experiment requires every
        artifact. It checks whether at least some meaningful experiment state
        is available.
        """
        checks: Dict[str, bool] = {}
        reasons: List[str] = []

        if context is None or context.artifacts is None:
            checks["artifacts_available"] = False

            reasons.append(
                "No experiment artifacts are currently attached to the context."
            )

            return 0.0, checks, reasons

        artifacts = context.artifacts

        dataset_available = artifacts.dataset is not None
        model_available = artifacts.model is not None
        logs_available = artifacts.training_logs is not None
        hyperparameters_available = bool(artifacts.hyperparameters)

        checks["dataset_available"] = dataset_available
        checks["model_available"] = model_available
        checks["training_logs_available"] = logs_available
        checks["hyperparameters_available"] = hyperparameters_available

        available_count = sum(
            [
                dataset_available,
                model_available,
                logs_available,
                hyperparameters_available,
            ]
        )

        if available_count > 0:
            checks["artifacts_available"] = True
            reasons.append(
                f"Experiment context contains {available_count} usable "
                f"artifact/configuration source(s)."
            )
        else:
            checks["artifacts_available"] = False
            reasons.append(
                "Experiment context does not contain usable artifacts."
            )

        # At least one artifact is sufficient for selection at this stage.
        # More detailed execution requirements will be validated by the
        # Experiment Executor later.
        score = available_count / 4.0

        return score, checks, reasons

    # -----------------------------------------------------------------------
    # Score calculation
    # -----------------------------------------------------------------------

    def _calculate_score(
        self,
        recommendation: ExperimentRecommendation,
        context: Optional[ExperimentContext],
        completeness_score: float,
        context_score: float,
        diagnosis_score: float,
        artifact_score: float,
    ) -> float:
        """
        Calculate the generic execution-readiness score.

        The calculation intentionally does not inspect recommendation text
        for specific strategies. This prevents the selector from becoming a
        hidden hardcoded recommendation engine.
        """
        title_score = 1.0 if recommendation.title.strip() else 0.0
        change_score = 1.0 if recommendation.change.strip() else 0.0
        reason_score = 1.0 if recommendation.reason.strip() else 0.0

        score = (
            title_score * SCORE_WEIGHTS["title"]
            + change_score * SCORE_WEIGHTS["change"]
            + reason_score * SCORE_WEIGHTS["reason"]
            + context_score * SCORE_WEIGHTS["context"]
            + diagnosis_score * SCORE_WEIGHTS["diagnosis"]
            + artifact_score * SCORE_WEIGHTS["artifacts"]
        )

        return max(0.0, min(1.0, score))

    # -----------------------------------------------------------------------
    # Utilities
    # -----------------------------------------------------------------------

    @staticmethod
    def _unique(values: List[str]) -> List[str]:
        """
        Preserve order while removing duplicate messages.
        """
        result: List[str] = []

        for value in values:
            normalized = value.strip()

            if normalized and normalized not in result:
                result.append(normalized)

        return result

    def __repr__(self) -> str:
        """
        Developer-friendly representation.
        """
        return (
            f"ExperimentSelector("
            f"minimum_score={self.minimum_score:.2f}"
            f")"
        )